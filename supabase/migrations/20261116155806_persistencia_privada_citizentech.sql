CREATE SCHEMA IF NOT EXISTS citizentech;
REVOKE ALL ON SCHEMA citizentech FROM PUBLIC;

CREATE TABLE citizentech.atendimentos (
    id TEXT PRIMARY KEY,
    origem_id TEXT UNIQUE,
    conteudo TEXT NOT NULL,
    ordem BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE citizentech.eventos (
    numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atendimento_id TEXT NOT NULL REFERENCES citizentech.atendimentos(id),
    conteudo TEXT NOT NULL
);

CREATE TABLE citizentech.envios (
    id TEXT PRIMARY KEY,
    atendimento_id TEXT NOT NULL REFERENCES citizentech.atendimentos(id),
    assinatura TEXT NOT NULL
);

CREATE TABLE citizentech.planos_passagem (
    id TEXT PRIMARY KEY,
    conteudo TEXT NOT NULL,
    ordem BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE citizentech.relatos (
    id TEXT PRIMARY KEY,
    cidadao_id TEXT NOT NULL,
    descricao TEXT NOT NULL,
    bairro TEXT NOT NULL,
    categoria TEXT NOT NULL,
    prioridade TEXT NOT NULL,
    resumo TEXT NOT NULL,
    status TEXT NOT NULL,
    observacao_gestor TEXT NOT NULL DEFAULT '',
    criado_em TEXT NOT NULL,
    atualizado_em TEXT NOT NULL
);
CREATE INDEX relatos_por_cidadao ON citizentech.relatos (cidadao_id, criado_em DESC);
CREATE INDEX eventos_por_atendimento ON citizentech.eventos (atendimento_id, numero);

ALTER TABLE citizentech.atendimentos ENABLE ROW LEVEL SECURITY;
ALTER TABLE citizentech.eventos ENABLE ROW LEVEL SECURITY;
ALTER TABLE citizentech.envios ENABLE ROW LEVEL SECURITY;
ALTER TABLE citizentech.planos_passagem ENABLE ROW LEVEL SECURITY;
ALTER TABLE citizentech.relatos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA citizentech FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA citizentech FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA citizentech REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA citizentech REVOKE ALL ON SEQUENCES FROM PUBLIC;

